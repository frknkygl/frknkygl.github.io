export const STARTER_HERO_IDS = ['malakor', 'toren', 'yrsa'];

export function heroStatAtLevel(hero: HeroDef, level: number) {
  const l = Math.max(1, level);
  return {
    atk: Math.round(hero.baseAtk + hero.growthAtk * (l - 1)),
    hp: Math.round(hero.baseHp + hero.growthHp * (l - 1)),
    def: Math.round(hero.baseDef + hero.growthDef * (l - 1)),
  };
}

export const MAX_HERO_LEVEL = 30;

export function heroUpgradeCost(level: number) {
  return {
    gold: Math.round(120 * Math.pow(level, 1.55)),
    shards: level < 10 ? 1 : level < 20 ? 2 : 3,
  };
}
